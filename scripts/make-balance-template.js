'use strict';
/* يولّد قالب شيت «الأرصدة» (بنفس أعمدة الملف المحمي) في مجلد المستندات */
const path = require('node:path');
const XLSX = require('xlsx');

const OUT = process.argv[2] ||
  path.join(__dirname, '..', 'قالب شيت الأرصدة.xlsx');

const HEADERS = [
  'تاريخ الرصيد', 'المادة', 'وصف المادة', 'وحدة القياس الأساسية',
  'رمز الشركة', 'الوحدة', 'موقع التخزين', 'العملة', 'نوع المادة',
  'كمية المخزون في بداية الفترة', 'القيمة في بداية الفترة',
  'كمية المخزون في نهاية الفترة', 'قيمة المخزون في نهاية الفترة',
];

const ws = XLSX.utils.aoa_to_sheet([HEADERS]);
ws['!cols'] = HEADERS.map(h => ({ wch: Math.max(13, h.length + 3) }));

const inst = XLSX.utils.aoa_to_sheet([
  ['قالب شيت «الأرصدة» — للاستيراد اليومي'],
  [],
  ['كيف تستعمل:'],
  [1, 'افتح ملفك اليومي «تسجيل حركات يومية.xlsx» وأضف ورقة جديدة باسم: الأرصدة'],
  [2, 'انسخ صف العناوين من ورقة «الأرصدة» هنا كما هو تماماً (13 عموداً بالترتيب)'],
  [3, 'كل يوم أضف صفوفاً بتواريخ ذلك اليوم: الصنف، الوحدة (المصنع)، الموقع، الكميات والقيم'],
  [4, 'التاريخ يُكتب بصيغة 2026-10-07 أو كخلية تاريخ — كلاهما يُقرأ'],
  [5, 'من التطبيق: تبويب الاستيراد ← «استيراد اليوم»'],
  [6, 'يُستبدل شيت الأرصدة «حسب التاريخ والمفتاح» فقط: الأيام السابقة تبقى محفوظة ولو حذفتها من الشيت'],
  [],
  ['ملاحظات:'],
  ['•', 'كل صف يحتاج الافتتاحي والختامي معاً (كمية وقيمة بداية + كمية وقيمة نهاية)'],
  ['•', 'لا تكرر نفس الصنف في نفس اليوم ونفس الوحدة والموقع — الصف المكرر يُجمع تلقائياً (SUM)'],
  ['•', 'لو النافذة في شيتك تمشي للأمام (يُحذف تاريخ قديم) تبقى الأيام القديمة في التطبيق كما هي'],
  ['•', 'بعد الاستيراد: تبويب جودة البيانات ← «إعادة الفحص» يتأكد أن نهاية سابق = بداية لاحق'],
]);
inst['!cols'] = [{ wch: 5 }, { wch: 110 }];

const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, ws, 'الأرصدة');
XLSX.utils.book_append_sheet(wb, inst, 'تعليمات');
XLSX.writeFile(wb, OUT);
console.log('تم الإنشاء:', OUT);
